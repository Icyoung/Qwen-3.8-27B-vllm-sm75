#!/usr/bin/env python3
"""Generate the one-output full Ultra build from its shared core and UI recipes."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
def render():
 core=(ROOT/'docker/Dockerfile').read_text()
 ultra=(ROOT/'ultra/Dockerfile').read_text()
 node=next(line for line in ultra.splitlines() if line.startswith('ARG NODE_IMAGE='))
 core=re.sub(r'^# syntax=.*\n','',core)
 core=core.replace('FROM verified-runtime AS final','FROM verified-runtime AS sm75-core')
 ultra='\n'.join(line for line in ultra.splitlines() if not line.startswith(('ARG VLLM_IMAGE=','ARG NODE_IMAGE=')))+'\n'
 ultra=ultra.replace('FROM ${VLLM_IMAGE}','FROM sm75-core AS final')
 ultra=ultra.replace('COPY harness/','COPY ultra/harness/').replace('harness/package-lock.json','ultra/harness/package-lock.json')
 ultra=ultra.replace('COPY source /','COPY ultra/source /').replace('COPY overlay/','COPY ultra/overlay/')
 return '# syntax=docker/dockerfile:1\n# Generated by tools/generate_ultra_dockerfile.py\n'+node+'\n'+core+'\n'+ultra
if __name__=='__main__':(ROOT/'docker/Dockerfile.ultra-full').write_text(render(),encoding='utf-8',newline='\n')
